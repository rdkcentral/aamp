// ============================================================================
// TestDrmHelper — minimal DrmHelper that returns a configurable single key
// ============================================================================
class FkTestDrmHelper : public DrmHelper
{
public:
	explicit FkTestDrmHelper(const std::vector<uint8_t>& psshKey)
		: DrmHelper(DrmInfo{}), mKey(psshKey), mSystemId(kWvSystemId)
	{
	}

	const std::string& ocdmSystemId() const override { return mSystemId; }

	void getKey(std::vector<uint8_t>& keyId) const override
	{
		keyId = mKey;
	}

	void getKeys(std::map<int, std::vector<uint8_t>>& keyIds) const override
	{
		// Return empty map so cacheFutureKeys falls back to getKey()
		keyIds.clear();
	}

	void createInitData(std::vector<uint8_t>& initData) const override
	{
		initData = mKey;
	}

	bool parsePssh(const uint8_t* initData, uint32_t initDataLen) override
	{
		if (initData && initDataLen > 0)
		{
			mKey.assign(initData, initData + initDataLen);
		}
		return true;
	}

	bool isClearDecrypt() const override { return true; }

	void generateLicenseRequest(
		const ChallengeInfo& challengeInfo,
		LicenseRequest& licenseRequest) const override
	{
		licenseRequest.method = LicenseRequest::POST;
		licenseRequest.url    = "http://test.example.com/license";
	}

private:
	std::vector<uint8_t> mKey;
	std::string          mSystemId;
};

