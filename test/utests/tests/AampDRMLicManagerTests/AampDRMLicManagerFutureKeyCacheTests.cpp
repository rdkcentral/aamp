/**
 * @file AampDRMLicManagerFutureKeyCacheTests.cpp
 * @brief L1 unit tests for AampDRMLicenseManager's future-key cache feature.
 *
 * The future-key cache allows a multi-key Widevine license response to
 * deliver keys for adaptation sets that have not yet been requested.  When
 * a subsequent DRM session requests one of those keys the manager returns
 * the cached license response without a network round-trip.
 *
 * Test data: a real 1736-byte Widevine SignedMessage that contains exactly
 * 8 KeyContainer entries.  The PSSH key for these tests is set to the first
 * entry (index 0) so that cacheFutureKeys stores exactly 7 future keys
 * (indices 1–7).
 *
 * Key IDs (binary, 16 bytes each):
 *   [0] 137da86e 8ea24f6f a3b84f88 33aeeca6  ← PSSH key (excluded from cache)
 *   [1] e31bac04 bd324e80 879971f8 5b65a8f9
 *   [2] f61f57aa b8b84b3e aae17018 2ce00968
 *   [3] 6c25de6e 060e472a 8da7ca53 cadddf78
 *   [4] 2dcf9acb ed484099 a70196ac 70d97b57
 *   [5] 6c75f994 7de548de 90f952e5 6ccf0bfe
 *   [6] 82e14db4 ac38404f 89521fb5 0d62b0f7
 *   [7] 2bdbb9c2 08be4022 8f190f9c eb8a2d1a
 */

