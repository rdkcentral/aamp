/**
 * @brief Cache miss on a freshly constructed manager.
 *
 * No caching has occurred yet; every lookup must return nullptr.
 */
TEST_F(FutureKeyCacheTests, CacheMissOnEmptyCache)
{
	auto result = mLicMgr->testFindCachedFutureKey(kKeyId1, kWvSystemId);
	EXPECT_EQ(result, nullptr)
		<< "Expected nullptr on empty cache for kKeyId1";

	result = mLicMgr->testFindCachedFutureKey(kKeyId0, kWvSystemId);
	EXPECT_EQ(result, nullptr)
		<< "Expected nullptr on empty cache for kKeyId0";
}

/**
 * @brief Parsing a real 8-key Widevine blob caches exactly 7 future keys.
 *
 * The helper's PSSH key is set to kKeyId0 (index 0 in the blob).
 * cacheFutureKeys must exclude kKeyId0 from the cache and store kKeyId1
 * through kKeyId7.
 */
TEST_F(FutureKeyCacheTests, ParsesRealWvBlob_CachesSevenFutureKeys)
{
	auto helper  = makeHelper(kKeyId0);
	auto licData = makeWvLicenseData();

	mLicMgr->testCacheFutureKeys(helper, /*slot=*/0, licData);

	// PSSH key (kKeyId0) must NOT be cached
	EXPECT_EQ(
		mLicMgr->testFindCachedFutureKey(kKeyId0, kWvSystemId),
		nullptr)
		<< "PSSH key kKeyId0 should NOT appear in the future cache";

	// All 7 remaining keys must be found
	const std::vector<std::reference_wrapper<const std::vector<uint8_t>>>
		futureKeys = {kKeyId1, kKeyId2, kKeyId3, kKeyId4,
		              kKeyId5, kKeyId6, kKeyId7};

	for (size_t i = 0; i < futureKeys.size(); ++i)
	{
		auto cached = mLicMgr->testFindCachedFutureKey(
			futureKeys[i].get(), kWvSystemId);
		EXPECT_NE(cached, nullptr)
			<< "Future key at index " << (i + 1)
			<< " not found in cache after caching";
	}
}

/**
 * @brief Cached license data length matches the original blob.
 *
 * Verifies that the deep-copy stored in the cache preserves all bytes.
 */
TEST_F(FutureKeyCacheTests, CachedLicenseDataMatchesOriginalBlob)
{
	auto helper  = makeHelper(kKeyId0);
	auto licData = makeWvLicenseData();

	mLicMgr->testCacheFutureKeys(helper, /*slot=*/0, licData);

	auto cached = mLicMgr->testFindCachedFutureKey(kKeyId1, kWvSystemId);
	ASSERT_NE(cached, nullptr);

	// The cached copy must have the same byte count as the original blob
	EXPECT_EQ(cached->getDataLength(), kWvLicBlobSize)
		<< "Cached DrmData length differs from original blob size";

	// And the content must be byte-identical
	EXPECT_EQ(
		std::memcmp(
			cached->getData().data(),
			kWvLicBlob,
			kWvLicBlobSize),
		0)
		<< "Cached DrmData content differs from original blob";
}

/**
 * @brief Calling cacheFutureKeys twice does not produce duplicate entries.
 *
 * The second call must be a no-op for keys already in the cache.
 */
TEST_F(FutureKeyCacheTests, NoDuplicateEntriesOnRepeatedCache)
{
	auto helper  = makeHelper(kKeyId0);
	auto licData = makeWvLicenseData();

	mLicMgr->testCacheFutureKeys(helper, /*slot=*/0, licData);
	mLicMgr->testCacheFutureKeys(helper, /*slot=*/0, licData);

	// Each future key must still be findable (no corruption)
	for (const auto& kid :
	     {kKeyId1, kKeyId2, kKeyId3, kKeyId4, kKeyId5, kKeyId6, kKeyId7})
	{
		auto cached = mLicMgr->testFindCachedFutureKey(kid, kWvSystemId);
		EXPECT_NE(cached, nullptr)
			<< "Key not found after duplicate caching attempt";
	}
}

/**
 * @brief clearFutureKeyCache evicts all entries.
 *
 * After clearing, every key that was previously cached must produce a miss.
 */
TEST_F(FutureKeyCacheTests, ClearFutureKeyCacheEvictsAllEntries)
{
	auto helper  = makeHelper(kKeyId0);
	auto licData = makeWvLicenseData();

	mLicMgr->testCacheFutureKeys(helper, /*slot=*/0, licData);

	// Pre-condition: at least one key is cached
	ASSERT_NE(
		mLicMgr->testFindCachedFutureKey(kKeyId1, kWvSystemId),
		nullptr)
		<< "Pre-condition failed: kKeyId1 not found before clear";

	mLicMgr->clearFutureKeyCache();

	// Post-condition: every key returns nullptr
	for (const auto& kid :
	     {kKeyId1, kKeyId2, kKeyId3, kKeyId4, kKeyId5, kKeyId6, kKeyId7})
	{
		EXPECT_EQ(
			mLicMgr->testFindCachedFutureKey(kid, kWvSystemId),
			nullptr)
			<< "Key still present in cache after clearFutureKeyCache";
	}
}

/**
 * @brief Key system isolation: lookup with a different system ID returns
 *        nullptr even when the key ID matches a cached entry.
 */
TEST_F(FutureKeyCacheTests, MissOnDifferentKeySystem)
{
	auto helper  = makeHelper(kKeyId0);
	auto licData = makeWvLicenseData();

	mLicMgr->testCacheFutureKeys(helper, /*slot=*/0, licData);

	// kKeyId1 is in the cache under kWvSystemId
	ASSERT_NE(
		mLicMgr->testFindCachedFutureKey(kKeyId1, kWvSystemId),
		nullptr)
		<< "Pre-condition: kKeyId1 must be cached under kWvSystemId";

	// Same key ID but wrong system must return nullptr
	auto result = mLicMgr->testFindCachedFutureKey(
		kKeyId1, "com.microsoft.playready");
	EXPECT_EQ(result, nullptr)
		<< "Cache must not return data for wrong DRM system";
}

/**
 * @brief Single-key license response (no future keys): cache stays empty.
 *
 * When the license contains only one key the implementation must skip
 * caching and produce a miss on any subsequent lookup.
 */
TEST_F(FutureKeyCacheTests, SingleKeyBlobProducesNoCache)
{
	// Minimal protobuf: SignedMessage.field2 → License.field3 → one key
	// field tag 0x12 (field 2, LEN), varint length, then
	// field tag 0x1a (field 3, LEN), varint length, KeyContainer(field1=16B)
	static const uint8_t kOneKeyBlob[] = {
		// SignedMessage: field 2 (msg), length = 22
		0x12, 0x16,
		// License: field 3 (key), length = 20
		0x1a, 0x14,
		// KeyContainer: field 1 (id), length = 16
		0x0a, 0x10,
		// 16-byte key ID (kKeyId1 bytes)
		0xe3, 0x1b, 0xac, 0x04, 0xbd, 0x32, 0x4e, 0x80,
		0x87, 0x99, 0x71, 0xf8, 0x5b, 0x65, 0xa8, 0xf9
	};

	auto helper  = makeHelper(kKeyId0);
	auto licData = std::make_shared<DrmData>(
		reinterpret_cast<const char*>(kOneKeyBlob),
		sizeof(kOneKeyBlob));

	mLicMgr->testCacheFutureKeys(helper, /*slot=*/0, licData);

	// Nothing should be cached
	EXPECT_EQ(
		mLicMgr->testFindCachedFutureKey(kKeyId1, kWvSystemId),
		nullptr)
		<< "Single-key response must not populate the future cache";
}
