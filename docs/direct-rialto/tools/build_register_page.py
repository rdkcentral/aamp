"""Build 11-workarounds-and-improvement-register.md from _register/*.md.

Edit the fragments (one per area) and _register/_shortlist.md, then run
this script; never edit the generated page by hand.
"""

import collections
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTER = ROOT / "_register"
OUTPUT = ROOT / "11-workarounds-and-improvement-register.md"

# Fragment tag -> (section title, owning page title), in page order.
AREAS = [
    ("ARCH", "Architecture, integration, build and testing",
     "Architecture and class model; Integration, configuration and build; "
     "Testing"),
    ("LIFE", "Lifecycle and state machine", "Lifecycle and state machine"),
    ("DATA", "Media data path", "Media data path"),
    ("FLUSH", "Flush, seek and pre-roll", "Flush and seek"),
    ("THR", "Threading and locking", "Threading model and locking"),
    ("DRM", "DRM", "DRM"),
    ("SUB", "Subtitles and closed captions", "Subtitles and TTML"),
    ("MON", "Monitoring, timers and position", "Monitoring and diagnostics"),
]
TYPES = ["Possible bug", "Workaround", "Limitation", "Stub", "Tech-debt",
         "Stale comment"]
ROW = re.compile(r"^\|\s*([A-Z]+-\d+)\s*\|")
HEADER = ("| ID | Location | Type | What and why | Risk/impact | "
          "Suggested improvement | Effort |\n|---|---|---|---|---|---|---|")


def read_rows(tag):
    rows = []
    for line in (REGISTER / (tag + ".md")).read_text(
            encoding="utf-8").splitlines():
        if ROW.match(line):
            cells = [c.strip() for c in re.split(r"(?<!\\)\|", line)[1:-1]]
            rows.append((line, cells))
    return rows


def main():
    counts = collections.OrderedDict()
    sections = []
    total = 0
    for tag, title, page in AREAS:
        rows = read_rows(tag)
        total += len(rows)
        per_type = collections.Counter(cells[2] for _, cells in rows)
        counts[tag] = (title, per_type, len(rows))
        body = "\n".join(line for line, _ in rows)
        sections.append(
            "## %s (%s)\n\nPage: Direct Rialto - %s. %d items.\n\n%s\n%s\n"
            % (title, tag, page, len(rows), HEADER, body))

    summary = ["| Area | " + " | ".join(TYPES) + " | Total |",
               "|---" * (len(TYPES) + 2) + "|"]
    for tag, (title, per_type, n) in counts.items():
        summary.append("| %s (%s) | %s | %d |" % (
            title, tag, " | ".join(str(per_type.get(t, 0)) for t in TYPES),
            n))
    grand = collections.Counter()
    for _, per_type, _ in counts.values():
        grand.update(per_type)
    summary.append("| **Total** | %s | **%d** |" % (
        " | ".join(str(grand.get(t, 0)) for t in TYPES), total))

    shortlist = (REGISTER / "_shortlist.md").read_text(encoding="utf-8")
    shortlist = re.sub(r"^# .*\n+", "", shortlist)
    shortlist = re.sub(r"^## ", "### ", shortlist, flags=re.M)

    page = """# Direct Rialto - Workarounds and improvement register

## Purpose

Every known workaround, limitation, stub, stale comment, possible bug and piece of technical debt in direct-rialto, together with the special cases it caused in AAMP core. Each row gives the location, why the code is the way it is, the risk, a suggested improvement and a rough effort (S: under a day, M: a few days, L: larger). Items were found while writing this documentation set and checked against the code; "Possible bug" means a plausible defect found by reading, not a confirmed field failure.

## How to use this page

- Start with the prioritised shortlist, then the full tables, which are grouped by area.
- IDs are stable and are referenced from the topic pages; when an item is fixed, mark it fixed (do not reuse the ID).
- Rows marked "Same item as" or "Part of" another ID are cross-references kept because a topic page cites them.
- Source: `docs/direct-rialto/_register/*.md`, one fragment per area, plus `_shortlist.md`. This page is generated by `docs/direct-rialto/tools/build_register_page.py`; edit the fragments, not this page.

## Prioritised shortlist

{shortlist}
## Summary by area and type

{summary}

{sections}
## Related pages

- Direct Rialto - Overview
- Direct Rialto - Troubleshooting and glossary
""".format(shortlist=shortlist.strip() + "\n", summary="\n".join(summary),
           sections="\n".join(sections))
    OUTPUT.write_text(page, encoding="utf-8")
    print("wrote %s (%d items)" % (OUTPUT.name, total))


if __name__ == "__main__":
    main()
